import Link from "next/link";
import { notFound } from "next/navigation";
import { requirePage } from "@/lib/auth/current";
import { getShow, seriesOf, SHOW_TYPE_LABEL } from "@/lib/shows";
import { listLedger, listTransactions } from "@/lib/finance/data";
import { categoryTotals, deriveSettleStatus, INCOME_CATEGORIES, MANUAL_EXPENSE_CATEGORIES, MEMBERS, showSplit } from "@/lib/finance/calc";
import { inferParticipants, SOURCE_LABEL } from "@/lib/finance/participants";
import { listLinesForShow } from "@/lib/finance/oen";
import { oenVsBooks } from "@/lib/finance/inbox";
import { hasTechFee, nextProcessingLabel } from "@/lib/finance/schedule";
import { formatMonthDay, todayInTaipei } from "@/lib/dates";
import { displayName } from "@/lib/auth/users";
import TopBar from "@/components/top-bar";
import TxBoard from "@/components/tx-board";
import ShowParticipants from "@/components/show-participants";

const money = (n: number) => `${n < 0 ? "−" : ""}$${Math.abs(Math.round(n)).toLocaleString()}`;
const cls = (n: number) => (n >= 0 ? "pos" : "neg");

// 演出財務詳細：類別明細、逐筆（可編輯）、每位成員分配預覽、Oen 票務摘要 vs 票房列
export default async function FinanceShowPage({ params }: PageProps<"/finance/shows/[id]">) {
  const { id } = await params;
  const me = await requirePage("finance", `/finance/shows/${id}`);
  const actor = `user:${me.id}` as const;
  const show = await getShow(actor, id);
  if (!show) notFound();
  const [allTx, repayments, lines] = await Promise.all([listTransactions(actor), listLedger(actor, "advance_repayments"), listLinesForShow(actor, id).catch(() => [])]);
  const today = todayInTaipei();
  const settle = deriveSettleStatus(allTx, repayments); // FIFO 要看該成員所有專案的代墊
  const txs = allTx.filter((t) => t.showId === id).sort((a, b) => (a.date !== b.date ? (a.date < b.date ? 1 : -1) : b.sortOrder - a.sortOrder));
  const income = txs.filter((t) => t.amount > 0).reduce((s, t) => s + t.amount, 0);
  const expense = txs.filter((t) => t.amount < 0).reduce((s, t) => s + t.amount, 0);
  const inferred = inferParticipants(show, txs);
  const cats = categoryTotals(txs);
  const split = showSplit(txs);
  const vs = lines.length ? oenVsBooks(lines.map((l) => ({ ...l, charge: l.charge })), txs) : null;
  const pendingHere = lines.filter((l) => l.bookingStatus === "pending").length;
  const series = seriesOf(show);
  const perf = show.kind === "performance";

  return (
    <main className="page">
      <TopBar
        me={me}
        title={show.name}
        back={{ href: "/finance/shows", label: "演出收支" }}
        sub={
          <>
            <span className="badge s-badge">{perf ? series : "非演出科目"}</span>
            {perf ? <span>・{SHOW_TYPE_LABEL[show.type]}{show.performanceDate ? `・${formatMonthDay(show.performanceDate)}演出` : ""}</span> : null}
            {perf && show.performanceDate && hasTechFee({ ...show, series }) && show.performanceDate >= today ? <span className="due soon">{nextProcessingLabel({ kind: "tech_fee", performanceDate: show.performanceDate }, today)}</span> : null}
          </>
        }
        actions={perf ? <Link className="btn btn-ghost btn-sm" href={`/shows/${id}`}>企劃頁</Link> : undefined}
      />
      <div className="content">
        <div className="grid-stats">
          <div className="card"><small>收入</small><span className="amount pos">{money(income)}</span></div>
          <div className="card"><small>成本</small><span className="amount neg">{money(expense)}</span></div>
          <div className="card wide"><small>淨利</small><span className={`amount ${cls(income + expense)}`}>{money(income + expense)}</span><em>{txs.length ? nextProcessingLabel({ kind: "booked" }, today) : ""}</em></div>
        </div>
        {pendingHere ? <Link className="notice" href="/finance/inbox">這場有 {pendingHere} 筆 Oen 明細待確認，{nextProcessingLabel({ kind: "oen_pending" }, today)} →</Link> : null}
        <ShowParticipants
          showId={id}
          showName={show.name}
          members={MEMBERS}
          configured={show.defaultExcludedMembers}
          inferred={{ included: inferred.included, sourceLabel: SOURCE_LABEL[inferred.source], needsReview: inferred.needsReview }}
          rowCount={txs.filter((t) => !t.autoGenerated && !t.paidByFund && t.category !== "平台手續").length}
        />

        <div className="two-col">
          <section>
            <div className="section"><h2>類別明細</h2><span>{cats.length} 類</span></div>
            {cats.length === 0 ? <p className="empty">還沒有收支</p> : (
              <table className="table mini flat">
                <tbody>
                  {cats.map((c) => <tr key={c.category}><td>{c.category}<small className="muted"> ×{c.count}</small></td><td className={cls(c.amount)}>{money(c.amount)}</td></tr>)}
                </tbody>
              </table>
            )}
          </section>
          <section>
            <div className="section"><h2>分潤預覽</h2><span>這場各分多少</span></div>
            <table className="table mini flat">
              <tbody>
                {split.map((s) => <tr key={s.member}><td>{s.member}{s.member === "傑哥" ? <small className="muted"> 年底一次領</small> : null}</td><td className={cls(s.amount)}>{money(s.amount)}</td></tr>)}
              </tbody>
            </table>
            <p className="fine">全員共同列先扣 20% 共同基金後 8 人均分；有排除成員的列由參與成員均分；共同基金支付的列不計。年度報表另以最大餘數法取整。</p>
          </section>
        </div>

        {vs ? (
          <section>
            <div className="section"><h2>Oen 票務摘要</h2><span>{lines.length} 列・已入帳 {vs.oen.booked + vs.oen.historical}・待確認 {vs.oen.pending}・略過 {vs.oen.skipped}</span></div>
            <div className="vs-grid">
              <div><small>Oen 已入帳列</small><b>張數 {vs.oen.qty}</b><span>收取 {money(vs.oen.gross)}・手續費 {money(-vs.oen.fee)}・退款 {money(-vs.oen.refund)}</span><span>淨額 <b>{money(vs.oen.net)}</b></span></div>
              <div><small>帳上 Oen 來源列</small><b>{money(vs.booksOenNet)}</b><span>票房列合計（含手動）{money(vs.booksBoxOffice)}</span>
                <span>差異 <b className={vs.diff !== 0 ? "neg" : "pos"}>{money(vs.diff)}</b>{vs.diff !== 0 ? "（Oen 淨額 − 帳上）" : "，一致"}</span></div>
            </div>
            {vs.oen.historical ? <p className="fine">{vs.oen.historical} 列是 ledger 建立前就已入帳的歷史列，帳上對應列沒有 Oen 來源鍵時差異會出現，不代表漏帳。</p> : null}
          </section>
        ) : null}

        <section>
          <div className="section"><h2>逐筆</h2><span>{txs.length} 筆・點一筆編輯</span></div>
          <TxBoard
            key={id}
            showId={id}
            showName={show.name}
            txs={txs.map((t) => ({
              id: t.id, category: t.category, notes: t.notes, amount: t.amount, advancedBy: t.advancedBy, excludedMembers: t.excludedMembers,
              date: t.date, recordedBy: t.recordedBy, paidByFund: t.paidByFund, autoGenerated: t.autoGenerated, settle: settle.get(t.id) ?? null,
            }))}
            members={MEMBERS}
            incomeCategories={INCOME_CATEGORIES}
            expenseCategories={MANUAL_EXPENSE_CATEGORIES}
            me={displayName(me)}
            today={today}
          />
        </section>
      </div>
    </main>
  );
}
