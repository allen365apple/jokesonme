// 匯出收支 CSV（spec: Login and export events：匯出財務資料要留操作紀錄）。
import { requireAction } from "@/lib/auth/current";
import { listTransactions } from "@/lib/finance/data";
import { logEvent } from "@/lib/audit";

// 自由文字（備註、登記人、墊款人…）以 = + - @ 或控制字元開頭時，Excel 會當公式執行；前面加單引號讓它變純文字。
// 數字欄（金額）不是字串，負數不會被加引號。
const cell = (v: unknown) => {
  if (v === null || v === undefined) return "";
  let s = String(v);
  if (typeof v === "string" && /^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export async function GET(): Promise<Response> {
  let me;
  try {
    me = await requireAction("finance");
  } catch {
    return new Response("forbidden", { status: 403 });
  }
  const txs = await listTransactions(`user:${me.id}`);
  const header = ["專案名稱", "分類", "備註", "金額", "墊款人", "排除成員", "日期", "登記人", "由共同基金支付", "系統自動", "ID", "來源鍵"];
  const lines = txs.map((t) => [t.showName, t.category, t.notes, t.amount, t.advancedBy ?? "", t.excludedMembers.join(","), t.date, t.recordedBy ?? "", t.paidByFund, t.autoGenerated, t.id, t.oenKey ?? ""].map(cell).join(","));
  await logEvent(`user:${me.id}`, "finance.export", { what: "transactions.csv", rows: txs.length });
  return new Response("﻿" + [header.join(","), ...lines].join("\n"), {
    headers: { "Content-Type": "text/csv; charset=utf-8", "Content-Disposition": `attachment; filename="jokesonme-transactions.csv"` },
  });
}
