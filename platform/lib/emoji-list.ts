export const EMOJI_GROUPS: EmojiGroup[] = RAW.map(({ key, label, rows }) => ({
  key,
  label,
  items: rows.map((row) => {
    const [emoji, ...words] = row.split(" ").filter(Boolean);
    return { emoji, name: words[0] ?? emoji, keywords: words };
  }),
}));

/** 依關鍵字搜尋（名稱、關鍵字、或直接貼 emoji）。空字串回傳 null，表示顯示全部分組。同一個 emoji 只回一次。 */
export function searchEmoji(query: string, groups: EmojiGroup[] = EMOJI_GROUPS): EmojiEntry[] | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  const seen = new Set<string>();
  const out: EmojiEntry[] = [];
  for (const g of groups) {
    for (const e of g.items) {
      if (seen.has(e.emoji)) continue;
      if (e.emoji === query.trim() || e.keywords.some((k) => k.toLowerCase().includes(q))) {
        seen.add(e.emoji);
        out.push(e);
      }
    }
  }
  return out;
}
