import { test } from "node:test";
import assert from "node:assert/strict";
import {
  categoryShares, commonFund, deriveSettleStatus, groupKey, inYear, memberEarnings, MEMBERS, normalizeExcluded,
  roundPreservingSum, taxReservesForShow, yearsOf, yearSummary, type Ledger, type Tx,
} from "./calc.ts";

let seq = 0;
const tx = (o: Partial<Tx>): Tx => ({
  id: `t${++seq}`, showName: "10 月號", category: "演出票房", notes: "", amount: 0, advancedBy: null, excludedMembers: [],
  date: "2026-10-01", recordedBy: null, paidByFund: false, autoGenerated: false, sortOrder: seq, ...o,
});
const led = (member: string, amount: number, date = "2026-10-05"): Ledger => ({ id: `l${++seq}`, member, amount, date, notes: "", sortOrder: seq });

test("代墊 FIFO：同一天依列順序沖銷，還款不夠時第一筆部分結清", () => {
  const a = tx({ amount: -300, advancedBy: "柏文", date: "2026-10-01", sortOrder: 10 });
  const b = tx({ amount: -500, advancedBy: "柏文", date: "2026-10-01", sortOrder: 11 });
  const c = tx({ amount: -200, advancedBy: "柏文", date: "2026-09-30", sortOrder: 99 });
  const st = deriveSettleStatus([b, a, c], [led("柏文", 400)]);
  assert.deepEqual(st.get(c.id), { status: "settled", reimbursedAmount: 200 }); // 日期最早先沖
  assert.deepEqual(st.get(a.id), { status: "partial", reimbursedAmount: 200 }); // 同日列順序較前
  assert.deepEqual(st.get(b.id), { status: "unsettled", reimbursedAmount: 0 });
});

test("稅務預留：依排除成員分組、取最新日期、四捨五入、忽略舊的自動預留與共同基金專案", () => {
  const rows = [
    tx({ amount: 10000, date: "2026-10-01" }),
    tx({ amount: 5050, date: "2026-10-03" }),
    tx({ amount: 2000, excludedMembers: ["傑哥", "柏文"], date: "2026-10-02" }),
    tx({ amount: -300, category: "稅務預留", autoGenerated: true }),
    tx({ amount: -800, category: "場地租借" }),
  ];
  assert.deepEqual(taxReservesForShow("10 月號", rows), [
    { excludedMembers: [], amount: -452, date: "2026-10-03" }, // round(15050 × 3%) = 451.5 → 452
    { excludedMembers: ["傑哥", "柏文"], amount: -60, date: "2026-10-02" },
  ]);
  assert.deepEqual(taxReservesForShow("共同基金支出", rows), []);
});

test("稅務預留：退款扣減同分組的基礎，平台手續費不扣，基礎最低為 0", () => {
  const rows = [
    tx({ amount: 10000, excludedMembers: ["柏文", "傑哥"], date: "2026-10-01" }), // 順序不同也是同一組
    tx({ amount: -2000, category: "退款", excludedMembers: ["傑哥", "柏文"], date: "2026-10-05" }),
    tx({ amount: -350, category: "平台手續", excludedMembers: [], date: "2026-10-01" }),
    tx({ amount: 1000, excludedMembers: [], date: "2026-10-01" }),
    tx({ amount: -1500, category: "退款", excludedMembers: [], date: "2026-10-06" }), // 退超過收入 → 基礎 0，不提列
  ];
  assert.deepEqual(taxReservesForShow("10 月號", rows), [
    { excludedMembers: ["傑哥", "柏文"], amount: -240, date: "2026-10-05" }, // (10000 − 2000) × 3%
  ]);
  // 收入分類的負數列（舊資料的手動退款）同樣扣減
  const legacy = [tx({ amount: 10000 }), tx({ amount: -4000, category: "演出票房", date: "2026-10-09" })];
  assert.deepEqual(taxReservesForShow("10 月號", legacy), [{ excludedMembers: [], amount: -180, date: "2026-10-09" }]);
});

test("共同基金：共同基金支付的支出不算共同支出，只算已動用；提撥取整、提撥＋可分配＝共同淨利", () => {
  const f = commonFund([tx({ amount: 10000 }), tx({ amount: -2000 }), tx({ amount: -1000, paidByFund: true })]);
  assert.equal(f.commonNetProfit, 8000);
  assert.equal(f.fundReserved, 1600);
  assert.equal(f.fundUsed, 1000);
  assert.equal(f.fundBalance, 600);
  assert.equal(f.distributableCommonNet, 6400);
  const g = commonFund([tx({ amount: 7901 })]);
  assert.equal(g.fundReserved, 1580); // 1580.2 → 1580
  assert.equal(g.distributableCommonNet, 6321);
});

test("共同基金只抽「排除成員為空」的列：專場票房、專場退款都不進基金", () => {
  const f = commonFund([
    tx({ amount: 10000 }),
    tx({ amount: 50000, excludedMembers: ["巧達", "芭樂", "又又", "兔子", "大弋", "竹節蟲"] }),
    tx({ amount: -500, category: "退款", excludedMembers: ["巧達", "芭樂", "又又", "兔子", "大弋", "竹節蟲"] }),
    tx({ amount: -1000, category: "平台手續" }), // 手續費 8 人分 → 共同支出
  ]);
  assert.equal(f.commonIncome, 10000);
  assert.equal(f.commonExpense, -1000);
  assert.equal(f.fundReserved, 1800);
});

test("成員分配：非共同收入只分給沒被排除的成員；結算與代墊分開計", () => {
  const rows = [tx({ amount: 8000 }), tx({ amount: 600, excludedMembers: ["巧達", "芭樂", "又又", "兔子", "大弋", "竹節蟲"] }), tx({ amount: -100, advancedBy: "柏文" })];
  const m = Object.fromEntries(memberEarnings(rows, [led("柏文", 500)], [led("柏文", 100)]).map((r) => [r.name, r]));
  // 共同淨利 (8000-100)=7900 × 80% / 8 = 790；柏文另得 600/2 = 300
  assert.equal(m["柏文"].annualNet, 1090);
  assert.equal(m["柏文"].settled, 500);
  assert.equal(m["柏文"].unsettledNet, 590);
  assert.equal(m["柏文"].advanceUnsettled, 0);
  assert.equal(m["巧達"].annualNet, 790);
});

test("成員分配：最大餘數法，8 人加總剛好等於可分配金額", () => {
  const rows = [tx({ amount: 1001 })]; // 可分配 800.8 → 801；每人 100.1
  const m = memberEarnings(rows, [], []);
  assert.equal(m.reduce((s, r) => s + r.annualNet, 0), 801);
  assert.deepEqual(m.map((r) => r.annualNet), [101, 100, 100, 100, 100, 100, 100, 100]);
  assert.ok(m.every((r) => Number.isInteger(r.annualNet)));
  assert.deepEqual(roundPreservingSum([0.5, 0.5, 0.5, 0.5]), [1, 1, 0, 0]);
  assert.deepEqual(roundPreservingSum([-2.3, -2.3, -2.4]), [-2, -2, -3]);
  assert.deepEqual(roundPreservingSum([]), []);
});

test("傑哥不是排除成員：拿完整一份，沒結算時未收款淨利 = 年度分配淨利", () => {
  const rows = [tx({ amount: 8000 }), tx({ amount: 1000, excludedMembers: ["柏文"] })];
  const m = Object.fromEntries(memberEarnings(rows, [led("巧達", 800)], []).map((r) => [r.name, r]));
  const commonShare = (8000 * 0.8) / 8; // 800
  assert.equal(m["傑哥"].annualNet, commonShare + Math.round(1000 / 7)); // 800 + 143 = 943（最大餘數法把餘數給前面的人）
  assert.equal(m["傑哥"].settled, 0);
  assert.equal(m["傑哥"].unsettledNet, m["傑哥"].annualNet);
  assert.equal(m["巧達"].unsettledNet, m["巧達"].annualNet - 800);
  assert.equal(m["柏文"].annualNet, 800);
  assert.equal(MEMBERS.includes("傑哥"), true);
});

test("年度：總表、基金、成員報表只算該台北日曆年；代墊累計到年底", () => {
  const rows = [
    tx({ amount: 10000, date: "2026-12-31" }),
    tx({ amount: 5000, date: "2027-01-01" }),
    tx({ amount: -300, advancedBy: "柏文", date: "2026-12-20" }),
    tx({ amount: -200, advancedBy: "柏文", date: "2027-01-05" }),
  ];
  const settlements = [led("柏文", 100, "2026-12-30"), led("柏文", 50, "2027-01-02")];
  const repayments = [led("柏文", 300, "2027-01-03")];

  assert.deepEqual(yearSummary(rows, "2026"), { totalIncome: 10000, totalExpense: -300, netProfit: 9700 });
  assert.deepEqual(yearSummary(rows, "2027"), { totalIncome: 5000, totalExpense: -200, netProfit: 4800 });
  assert.equal(yearSummary(rows).totalIncome, 15000); // 不給年份 = 全歷史（對帳用）
  assert.equal(commonFund(rows, "2026").commonNetProfit, 9700);

  const m26 = Object.fromEntries(memberEarnings(rows, settlements, repayments, "2026").map((r) => [r.name, r]));
  assert.equal(m26["柏文"].annualNet, 970);
  assert.equal(m26["柏文"].settled, 100);
  assert.equal(m26["柏文"].unsettledNet, 870);
  assert.equal(m26["柏文"].advanceTotal, 300); // 2026 年底為止的代墊
  assert.equal(m26["柏文"].advanceCleared, 0); // 2027 才還
  const m27 = Object.fromEntries(memberEarnings(rows, settlements, repayments, "2027").map((r) => [r.name, r]));
  assert.equal(m27["柏文"].annualNet, 480);
  assert.equal(m27["柏文"].settled, 50);
  assert.equal(m27["柏文"].advanceTotal, 500);
  assert.equal(m27["柏文"].advanceCleared, 300);
  assert.equal(m27["柏文"].advanceUnsettled, 200);

  assert.deepEqual(inYear(rows, "2027").map((t) => t.amount), [5000, -200]);
  assert.deepEqual(yearsOf(rows, "2028"), ["2028", "2027", "2026"]);
});

test("排除成員：正規化去重排序、分組鍵不分順序、非成員與全排除丟錯", () => {
  assert.deepEqual(normalizeExcluded([" 柏文", "傑哥", "柏文"]), ["傑哥", "柏文"]);
  assert.deepEqual(normalizeExcluded([]), []);
  assert.equal(groupKey(["柏文", "傑哥"]), groupKey(["傑哥", "柏文"]));
  assert.equal(groupKey(["某人", "傑哥"]), "傑哥,某人"); // 舊資料的非成員也能分組，不丟錯
  assert.throws(() => normalizeExcluded(["傑哥", "某人"]), /不是成員/);
  assert.throws(() => normalizeExcluded([...MEMBERS]), /至少要有一位/);
});

test("分類佔比：未知分類歸到其他、依佔比排序", () => {
  const r = categoryShares([tx({ amount: 300, category: "演出票房" }), tx({ amount: 100, category: "神秘收入" }), tx({ amount: -50 })], "income");
  assert.deepEqual(r.map((c) => [c.name, c.amount, Math.round(c.pct)]), [["演出票房", 300, 75], ["其他收入", 100, 25]]);
});
