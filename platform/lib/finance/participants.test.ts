import { test } from "node:test";
import assert from "node:assert/strict";
import { inferParticipants, membersFromShowName } from "./participants.ts";

const row = (o: { category?: string; amount: number; excludedMembers?: string[]; autoGenerated?: boolean; paidByFund?: boolean }) => ({
  category: "演出票房", excludedMembers: [], autoGenerated: false, paidByFund: false, ...o,
});
const six = ["巧達", "芭樂", "又又", "兔子", "大弋", "竹節蟲"];

test("專案設定優先，且會正規化", () => {
  const p = inferParticipants({ name: "2026 支薪好友喜劇專場", defaultExcludedMembers: ["柏文", "傑哥"] }, [row({ amount: 100, excludedMembers: six })]);
  assert.deepEqual(p, { excludedMembers: ["傑哥", "柏文"], included: six, source: "config", needsReview: false });
});

test("沒設定就沿用既有票房列（最多列的那一組；手續費、系統列、支出不算）", () => {
  const rows = [
    row({ amount: 500, excludedMembers: six }),
    row({ amount: 500, excludedMembers: six }),
    row({ amount: 90000, excludedMembers: [] }), // 只有一列，輸給兩列
    row({ amount: -19, category: "平台手續", excludedMembers: [] }),
    row({ amount: -30, category: "稅務預留", autoGenerated: true, excludedMembers: [] }),
  ];
  const p = inferParticipants({ name: "隨便", defaultExcludedMembers: null }, rows);
  assert.equal(p.source, "rows");
  assert.deepEqual(p.included, ["傑哥", "柏文"]);
});

test("名稱推測：支薪好友 = 傑哥＋柏文；不認識的專場 → 全員並標記需確認；月號 → 全員不標記", () => {
  assert.deepEqual(membersFromShowName("2026 支薪好友專場 TRY OUT"), ["傑哥", "柏文"]);
  assert.deepEqual(membersFromShowName("2026 又兔了喜劇專場 《續杯》"), ["又又", "兔子"]);
  assert.equal(membersFromShowName("看我笑話｜第 2 季 11 月號"), null);
  const named = inferParticipants({ name: "2026 好竹弋漫才專場 《直球》", type: "special" }, []);
  assert.deepEqual(named.excludedMembers, ["傑哥", "柏文", "巧達", "芭樂", "又又", "兔子"]);
  assert.equal(named.source, "name");
  const unknown = inferParticipants({ name: "2027 神秘專場", type: "special" }, []);
  assert.deepEqual(unknown, { excludedMembers: [], included: [...["傑哥", "柏文"], ...six], source: "default", needsReview: true });
  const monthly = inferParticipants({ name: "看我笑話｜第 2 季 11 月號", type: "monthly" }, []);
  assert.equal(monthly.needsReview, false);
  assert.equal(monthly.source, "default");
});
