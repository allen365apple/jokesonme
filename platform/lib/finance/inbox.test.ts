import { test } from "node:test";
import assert from "node:assert/strict";
import { groupInbox, oenVsBooks, sumLines, type InboxLine } from "./inbox.ts";
import type { Tx } from "./calc.ts";

let seq = 0;
const line = (o: Partial<InboxLine> & { showId: string | null }): InboxLine => ({
  id: ++seq, lineType: "ticket", itemText: "票", qty: 1, txCategory: "演出票房", gross: 1000, fee: 35, refund: 0, net: 965, reconBatch: null, mapConfidence: "確定",
  charge: { chargeNo: `C${seq}`, paidAt: `2026-10-${String(10 + seq).padStart(2, "0")}T02:00:00Z`, status: "付款成功", payoutStatus: "未撥款", eventName: null },
  ...o,
});
const tx = (o: Partial<Tx>): Tx => ({
  id: `t${++seq}`, showName: "A", category: "演出票房", notes: "", amount: 0, advancedBy: null, excludedMembers: [], date: "2026-10-01", recordedBy: null, paidByFund: false, autoGenerated: false, sortOrder: seq, ...o,
});

test("合計", () => {
  assert.deepEqual(sumLines([line({ showId: "a" }), line({ showId: "a", gross: 500, fee: 10, refund: 100, net: 390, qty: 2 })]), { lines: 2, qty: 3, gross: 1500, fee: 45, refund: 100, net: 1355 });
});

test("依演出分組：對不到的最後、組內新到舊、旗標與既有票房合計", () => {
  seq = 0;
  const lines = [
    line({ showId: "b" }),
    line({ showId: "a", mapConfidence: "推測" }),
    line({ showId: null }),
    line({ showId: "a", charge: { chargeNo: "X", paidAt: "2026-10-30T02:00:00Z", status: "已退款", payoutStatus: "無金流", eventName: null } }),
  ];
  const txs = new Map([["a", [tx({ amount: 3000 }), tx({ amount: -90, category: "稅務預留", autoGenerated: true }), tx({ amount: 200, category: "周邊商品" })]]]);
  const groups = groupInbox(lines, txs, (id) => (id === "a" ? 0 : 1));
  assert.deepEqual(groups.map((g) => g.showId), ["a", "b", null]);
  const a = groups[0];
  assert.deepEqual(a.lines.map((l) => l.charge.chargeNo), ["X", "C2"]);
  assert.equal(a.unpaid, 1);
  assert.equal(a.noCashflow, 1);
  assert.equal(a.guessed, 1);
  assert.equal(a.nonSuccess, 1);
  assert.equal(a.existingBoxOffice, 3200);
  assert.equal(a.existingBoxOfficeRows, 2);
  assert.equal(groups[1].existingBoxOffice, 0);
});

test("Oen 摘要 vs 帳上：只算已入帳與歷史列；差異 = Oen 淨額 − 帳上 Oen 來源列", () => {
  const lines = [
    { ...line({ showId: "a" }), bookingStatus: "booked" },
    { ...line({ showId: "a", gross: 2000, fee: 70, net: 1930 }), bookingStatus: "historical" },
    { ...line({ showId: "a" }), bookingStatus: "pending" },
    { ...line({ showId: "a" }), bookingStatus: "skipped" },
  ];
  const txs = [
    { ...tx({ amount: 1000 }), oenKey: "oen:C1:income" }, { ...tx({ amount: -35, category: "平台手續" }), oenKey: "oen:C1:fee" },
    { ...tx({ amount: 2000 }), oenKey: "oen:C2:income" }, // 歷史列的手續費沒入帳 → 差 -70
    { ...tx({ amount: 500 }), oenKey: null }, // 手動票房
  ];
  const r = oenVsBooks(lines, txs);
  assert.deepEqual([r.oen.booked, r.oen.pending, r.oen.skipped, r.oen.historical], [1, 1, 1, 1]);
  assert.equal(r.oen.net, 2895);
  assert.equal(r.booksOenNet, 2965);
  assert.equal(r.booksBoxOffice, 3500);
  assert.equal(r.diff, -70);
});
