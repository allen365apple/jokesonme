// 專案參與成員（誰分這個專案的票房與退款）。應援匯入不再一律寫「全員共同」，改依序推測：
//   1. 專案設定（shows.default_excluded_members；null = 未設定）
//   2. 該專案現有票房列的排除成員（最多列的那一組）
//   3. 專案名稱對照表（專場名字裡就寫了誰的場）
//   4. 都沒有 → 全員共同；若看起來是專場，標記「需人工確認」讓匯入摘要與畫面提醒
import { groupKey, isIncomeCategory, MEMBERS, normalizeExcluded, sortExcluded, type Tx } from "./calc.ts";

export type ParticipantSource = "config" | "rows" | "name" | "default";
export type Participants = {
  excludedMembers: string[]; // 寫進 transactions.excluded_members 的值
  included: string[]; // 給畫面看的參與者
  source: ParticipantSource;
  needsReview: boolean;
};

/** 專場名稱 → 參與成員。新的專場組合加在這裡（名稱片段用正則，大小寫不拘）。 */
export const SPECIAL_SHOW_MEMBERS: ReadonlyArray<{ pattern: RegExp; members: readonly string[] }> = [
  { pattern: /支薪好友/, members: ["傑哥", "柏文"] },
  { pattern: /又兔了/, members: ["又又", "兔子"] },
  { pattern: /好竹弋/, members: ["大弋", "竹節蟲"] },
];

export const SOURCE_LABEL: Record<ParticipantSource, string> = {
  config: "專案設定", rows: "沿用既有票房列", name: "依專案名稱推測", default: "預設全員",
};

export function membersFromShowName(name: string): string[] | null {
  const hit = SPECIAL_SHOW_MEMBERS.find((r) => r.pattern.test(name));
  return hit ? MEMBERS.filter((m) => hit.members.includes(m)) : null;
}

export const includedOf = (excluded: readonly string[]): string[] => MEMBERS.filter((m) => !excluded.includes(m));
const looksSpecial = (show: { name: string; type?: string | null }) => show.type === "special" || /專場/.test(show.name);

type ShowLike = { name: string; type?: string | null; defaultExcludedMembers?: string[] | null };
type RowLike = Pick<Tx, "category" | "amount" | "excludedMembers" | "autoGenerated" | "paidByFund">;

/** 票房列：收入分類、正數、非系統、非基金支付。 */
export const isBoxOfficeRow = (t: RowLike): boolean => t.amount > 0 && isIncomeCategory(t.category) && !t.autoGenerated && !t.paidByFund;

export function inferParticipants(show: ShowLike, rows: ReadonlyArray<RowLike>): Participants {
  const done = (excluded: string[], source: ParticipantSource, needsReview = false): Participants =>
    ({ excludedMembers: excluded, included: includedOf(excluded), source, needsReview });

  if (show.defaultExcludedMembers) return done(normalizeExcluded(show.defaultExcludedMembers), "config");

  const counts = new Map<string, { excluded: string[]; n: number; total: number }>();
  for (const t of rows) {
    if (!isBoxOfficeRow(t)) continue;
    const k = groupKey(t.excludedMembers);
    const c = counts.get(k) ?? { excluded: sortExcluded(t.excludedMembers), n: 0, total: 0 };
    c.n += 1;
    c.total += t.amount;
    counts.set(k, c);
  }
  const best = [...counts.values()].sort((a, b) => b.n - a.n || b.total - a.total)[0];
  if (best) return done(best.excluded, "rows");

  const named = membersFromShowName(show.name);
  if (named) return done(MEMBERS.filter((m) => !named.includes(m)), "name");

  return done([], "default", looksSpecial(show));
}
