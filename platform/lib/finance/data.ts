// 財務資料的讀取與寫入（伺服器端）。所有寫入以本人為 actor（x-actor header 會跟著 RPC 進到資料庫，audit trigger 照記）。
// 寫收支與重算稅務預留合併在資料庫函式裡（supabase/migrations/0013_finance_rules.sql），同一交易、失敗就全部不寫。
import { db, type Actor } from "../supabase.ts";
import type { Ledger, Tx } from "./calc.ts";

export type TxRow = Tx & { showId: string; oenKey: string | null };

type DbTx = {
  id: string; show_id: string; category: string; notes: string; amount: string | number; advanced_by: string | null;
  excluded_members: string[]; date: string; recorded_by: string | null; paid_by_fund: boolean; auto_generated: boolean;
  sort_order: number; oen_key: string | null; shows: { name: string } | null;
};
const TX_SELECT = "id, show_id, category, notes, amount, advanced_by, excluded_members, date, recorded_by, paid_by_fund, auto_generated, sort_order, oen_key, shows(name)";

function toTx(r: DbTx): TxRow {
  return {
    id: r.id, showId: r.show_id, showName: r.shows?.name ?? "", category: r.category, notes: r.notes, amount: Number(r.amount),
    advancedBy: r.advanced_by, excludedMembers: r.excluded_members ?? [], date: r.date, recordedBy: r.recorded_by,
    paidByFund: r.paid_by_fund, autoGenerated: r.auto_generated, sortOrder: Number(r.sort_order), oenKey: r.oen_key ?? null,
  };
}

const PAGE = 1000;
/**
 * Supabase（PostgREST）一次最多回 1000 列，超過會被默默截斷（2026-11-07：1,213 筆收支只讀到 1000 筆，分潤少算）。
 * 用 .range 一頁一頁讀，直到某頁不足一頁為止。page(from, to) 每頁都要建新的查詢，
 * 排序也要能唯一決定順序（最後補 id），不然換頁時同值的列可能重複或漏掉。
 */
async function readAllPages<T>(label: string, page: (from: number, to: number) => PromiseLike<{ data: T[] | null; error: { message: string } | null }>): Promise<T[]> {
  const out: T[] = [];
  for (let from = 0; ; from += PAGE) {
    const { data, error } = await page(from, from + PAGE - 1);
    if (error) throw new Error(`${label}: ${error.message}`);
    const rows = data ?? [];
    out.push(...rows);
    if (rows.length < PAGE) return out;
  }
}

export async function listTransactions(actor: Actor, showId?: string): Promise<TxRow[]> {
  const client = db(actor);
  const rows = await readAllPages<DbTx>("list transactions", (from, to) => {
    let q = client.from("transactions").select(TX_SELECT).is("deleted_at", null).order("sort_order").order("id");
    if (showId) q = q.eq("show_id", showId);
    return q.range(from, to).returns<DbTx[]>();
  });
  return rows.map(toTx);
}

export type LogRow = TxRow & { createdAt: string; legacy: boolean; addedBy: string | null; deletedAt: string | null; deletedBy: string | null };

/**
 * 逐筆紀錄（對帳用）：依加入順序由新到舊，跨所有專案。
 * 加入者以操作紀錄（audit_log 的 INSERT）為準，對不到才退回登記人；10/3 從舊表搬入的列 legacy=true（舊表沒有加入時間）。
 */
export async function listRecentTransactions(actor: Actor, limit: number, includeDeleted: boolean): Promise<LogRow[]> {
  const client = db(actor);
  let q = client
    .from("transactions")
    .select(`${TX_SELECT}, created_at, deleted_at, deleted_by`)
    .order("created_at", { ascending: false })
    .order("sort_order", { ascending: false })
    .limit(limit);
  if (!includeDeleted) q = q.is("deleted_at", null);
  const { data, error } = await q.returns<(DbTx & { created_at: string; deleted_at: string | null; deleted_by: string | null })[]>();
  if (error) throw new Error(`list recent transactions: ${error.message}`);
  const rows = data ?? [];

  const { data: inserts, error: e1 } = await client
    .from("audit_log")
    .select("row_id, actor")
    .eq("table_name", "transactions")
    .eq("op", "INSERT")
    .in("row_id", rows.map((r) => r.id));
  if (e1) throw new Error(`read audit_log: ${e1.message}`);
  const actorOf = new Map((inserts ?? []).map((a: { row_id: string; actor: string }) => [a.row_id, a.actor]));
  const userIds = [...new Set([...actorOf.values()].filter((a) => a.startsWith("user:")).map((a) => a.slice(5)))];
  const { data: users, error: e2 } = userIds.length
    ? await client.from("users").select("id, member_name, display_name").in("id", userIds)
    : { data: [], error: null };
  if (e2) throw new Error(`read users: ${e2.message}`);
  const nameOf = new Map((users ?? []).map((u: { id: string; member_name: string | null; display_name: string }) => [u.id, u.member_name || u.display_name]));

  return rows.map((r) => {
    const a = actorOf.get(r.id);
    const legacy = a === "migration";
    // 稅務預留是有人存收入時順手產生的，算在「系統」名下才不會被誤認成那個人手動加的
    const addedBy = r.auto_generated ? "系統" : a?.startsWith("user:") ? (nameOf.get(a.slice(5)) ?? r.recorded_by) : r.recorded_by;
    return { ...toTx(r), createdAt: r.created_at, legacy, addedBy, deletedAt: r.deleted_at, deletedBy: r.deleted_by };
  });
}

export async function listLedger(actor: Actor, table: "settlements" | "advance_repayments"): Promise<Ledger[]> {
  type DbLedger = { id: string; member: string; amount: string | number; date: string; notes: string; sort_order: number; for_year?: number | null };
  const client = db(actor);
  // 只有成員結算有分潤年度（0016 settlements.for_year）
  const columns = table === "settlements" ? "id, member, amount, date, notes, sort_order, for_year" : "id, member, amount, date, notes, sort_order";
  const rows = await readAllPages<DbLedger>(`list ${table}`, (from, to) =>
    client.from(table).select(columns).is("deleted_at", null).order("sort_order").order("id").range(from, to).returns<DbLedger[]>(),
  );
  return rows.map((r) => ({
    id: r.id, member: r.member, amount: Number(r.amount), date: r.date, notes: r.notes, sortOrder: Number(r.sort_order),
    ...(r.for_year == null ? {} : { forYear: String(r.for_year) }),
  }));
}

// ---- 寫入（全部走資料庫函式，寫入＋重算稅務預留同一交易） ----

/** Supabase 把資料庫丟出的錯誤原文放在 message；raise exception 的中文訊息直接給畫面看。 */
async function rpc<T>(actor: Actor, fn: string, args: Record<string, unknown>): Promise<T> {
  const { data, error } = await db(actor).rpc(fn, args);
  if (error) throw new Error(error.message);
  return data as T;
}

/** 重算某專案的稅務預留（舊 GAS recalcTaxReserveForShow 的等價版本，現在在資料庫裡做）。 */
export async function syncTaxReserve(actor: Actor, showId: string): Promise<void> {
  await rpc(actor, "finance_sync_tax_reserve", { p_show_id: showId });
}

export type ImportRow = {
  show_id: string; category: string; notes: string; amount: number; date: string;
  excluded_members: string[]; recorded_by: string; oen_key: string;
};
export type ImportResult = { inserted: number; skipped: number };
/** 應援匯入：同 oen_key 已存在（未刪除）的列略過，其餘寫入，受影響專案重算；一個交易。 */
export async function importTransactions(actor: Actor, rows: ImportRow[]): Promise<ImportResult> {
  const r = await rpc<{ inserted: number; skipped: number }>(actor, "finance_import_transactions", { p_rows: rows });
  return { inserted: Number(r?.inserted ?? 0), skipped: Number(r?.skipped ?? 0) };
}

export type TxWrite = {
  category: string; notes: string; amount: number; advanced_by: string | null; excluded_members: string[];
  date: string; recorded_by: string | null; paid_by_fund: boolean;
};
/** 手動新增（id 為空）或編輯一筆，回傳 id。 */
export async function saveTransactionRow(actor: Actor, id: string | null, showId: string | null, row: TxWrite): Promise<string> {
  return rpc<string>(actor, "finance_save_transaction", { p_id: id, p_show_id: showId, p_row: row });
}

export async function softDeleteTransaction(actor: Actor, id: string, deletedBy: string): Promise<void> {
  await rpc(actor, "finance_delete_transaction", { p_id: id, p_deleted_by: deletedBy });
}

/** 專案參與成員：excluded = null 表示清除設定（回到匯入時推測）。applyToRows 會把現有收支（手續費除外）一起改掉。 */
export async function setShowParticipants(actor: Actor, showId: string, excluded: string[] | null, applyToRows: boolean): Promise<{ updated: number }> {
  const r = await rpc<{ updated: number }>(actor, "finance_set_show_participants", { p_show_id: showId, p_excluded: excluded, p_apply_to_rows: applyToRows });
  return { updated: Number(r?.updated ?? 0) };
}
